package periytymisesimerki;

public class LainaTili {
    private double korko;
    private int lainaAlkuVuosi;

    public LainaTili() {
        super();
    }
    public LainaTili(double korko, int lainaAlkuVuosi) {
        super(saldo, nimi, tilinumero);
        this.korko = korko;
        this.lainaAlkuVuosi = lainaAlkuVuosi;
    }
    public double getKorko() {
        return korko;
    }
    public int getLainaAlkuVuosi() {
        return lainaAlkuVuosi;
    }
    

}
